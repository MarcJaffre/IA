#!/usr/bin/bash

# ====================================================================================================================================================================================
# Arrête le script immédiatement en cas d'erreur #
# ============================================== #
set -e

# ====================================================================================================================================================================================
# Fichier Configuration #
# ===================== #
FUNC_CONFIG(){
# Ne pas être dans IA !
if [ ! -f ./IA/config/globale.conf ]; then
# =========================================================================
  mv ./IA/config/globale.conf.exemple          ./IA/config/globale.conf;
  sed -i -e "s|WORKDIR=.*|WORKDIR=${PWD}/IA|g" ./IA/config/globale.conf;
# =========================================================================
else
 echo "Le fichier de configuration a échoué";
fi
}

exit;

# ====================================================================================================================================================================================
# Fonction d'affichage et de saisie
clear;
FUNC_MENU_SELECTION() {
    clear
    echo "================================================="
    echo "          MENU PRINCIPAL                         "
    echo "================================================="
    echo "0) Menu 0 : Check"
    echo "1) Menu 1 : Installation Dependances"
    echo "2) Menu 2 : Installation de LLAMA"
    #echo "3) Menu 3 : Installation de OpenWebui"
    echo "q) Quitter"
    echo "================================================="
    # Lecture de la réponse sur la même ligne
    echo "";
    read -p "Sélectionner votre choix ? " REPONSE
}
# ====================================================================================================================================================================================
# Fonction gérant la boucle et le traitement du choix
FUNC_CHOIX() {
    while true; do
        # Appel de l'affichage du menu
        FUNC_MENU_SELECTION
        # Analyse de la variable $REPONSE
        case "$REPONSE" in
            0)
            # ========================================================================================================
                ls ./IA/config;
                echo "";
                echo "---------------------------------------------------------------------------";
                read -p "Appuyez sur Entrée pour continuer..."
                ;;
            # ========================================================================================================

            1)
            # ========================================================================================================
                bash ./IA/workspaces/debian_base.sh 1>/dev/null;
                echo "";
                echo "---------------------------------------------------------------------------";
                read -p "Appuyez sur Entrée pour continuer..."
                ;;
            # ========================================================================================================


            2)
            # ========================================================================================================
                echo "-> Vous avez choisi le Menu 2."
                read -p "Appuyez sur Entrée pour continuer..."
                ;;
            # ========================================================================================================


            #3)
            # ========================================================================================================
            #    echo "-> Vous avez choisi le Menu 3."
            #    read -p "Appuyez sur Entrée pour continuer..."
            #    ;;
            # ========================================================================================================


            q|Q)
            # ========================================================================================================
                echo "Fermeture du menu. Au revoir !"
                break
                ;;
            # ========================================================================================================


            *)
            # ========================================================================================================
                echo "Erreur : Choix invalide ($REPONSE). Veuillez réessayer."
                sleep 2
                ;;
            # ========================================================================================================
        esac
    done
}
# ====================================================================================================================================================================================
# Lancement du script #
# =================== #
FUNC_CONFIG;
FUNC_CHOIX;
