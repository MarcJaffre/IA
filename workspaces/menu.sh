#!/usr/bin/bash

# ====================================================================================================================================================================================
# Arrête le script immédiatement en cas d'erreur #
# ============================================== #
set -e

# ====================================================================================================================================================================================
# Nettoyage Console #
#####################
clear;

# ====================================================================================================================================================================================
# Définir la variable WORKDIR #
# =========================== #
BASE_WORKDIR_VAR(){
if [[ "$PWD" != *IA* ]]; then
 WORKDIR=$PWD/IA
fi
}

# ====================================================================================================================================================================================
# Fichier Configuration #
# ===================== #
BASE_CONFIG(){
# Ne pas être dans IA !
if [ ! -f ${WORKDIR}/config/globale.conf ]; then
# =========================================================================
  mv ${WORKDIR}/config/globale.conf.exemple     ${WORKDIR}/globale.conf;
  sed -i -e "s|WORKDIR=.*|WORKDIR=${WORKDIR}|g" ${WORKDIR}/globale.conf;
  ls $WORKDIR/config
  grep 'WORKDIR=' $WORKDIR/config/globale.conf;
# =========================================================================
else
 echo "Le fichier de configuration a échoué";
fi
}


# ====================================================================================================================================================================================
# Fonction d'affichage et de saisie
clear;
BASE_MENU_SELECTION() {
    clear
    echo "================================================="
    echo "          MENU PRINCIPAL                         "
    echo "================================================="
    echo "0) Menu 0 : Check"
    echo "1) Menu 1 : Installation Dependances"
    echo "2) Menu 2 : Installation de LLAMA"
    #echo "3) Menu 3 : Installation de OpenWebui"
    echo "q) Quitter"
    echo "================================================="
    # Lecture de la réponse sur la même ligne
    echo "";
    read -p "Sélectionner votre choix ? " REPONSE
}


# ====================================================================================================================================================================================
# Fonction gérant la boucle et le traitement du choix
BASE_CHOIX() {
    while true; do
        # Appel de l'affichage du menu
        BASE_MENU_SELECTION
        # Analyse de la variable $REPONSE
        case "$REPONSE" in
            0)
            # ========================================================================================================
                ls ./IA/config;
                echo "";
                echo "---------------------------------------------------------------------------";
                read -p "Appuyez sur Entrée pour continuer..."
                ;;
            # ========================================================================================================

            1)
            # ========================================================================================================
                bash ./IA/workspaces/0_Base/Install_Packages.sh 1>/dev/null;
                echo "";
                echo "---------------------------------------------------------------------------";
                read -p "Appuyez sur Entrée pour continuer..."
                ;;
            # ========================================================================================================


            2)
            # ========================================================================================================
                echo "-> Vous avez choisi le Menu 2."
                read -p "Appuyez sur Entrée pour continuer..."
                ;;
            # ========================================================================================================


            #3)
            # ========================================================================================================
            #    echo "-> Vous avez choisi le Menu 3."
            #    read -p "Appuyez sur Entrée pour continuer..."
            #    ;;
            # ========================================================================================================


            q|Q)
            # ========================================================================================================
                echo "Fermeture du menu. Au revoir !"
                break
                ;;
            # ========================================================================================================


            *)
            # ========================================================================================================
                echo "Erreur : Choix invalide ($REPONSE). Veuillez réessayer."
                sleep 2
                ;;
            # ========================================================================================================
        esac
    done
}
# ====================================================================================================================================================================================
# Lancement du script #
# =================== #
BASE_WORKDIR_VAR;
echo $WORKDIR
ls ${WORKDIR}/config

