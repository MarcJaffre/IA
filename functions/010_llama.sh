###################################################################################
# Etape 0: Nettoyer le depot #
##############################
GIT_LLAMA_REMOVE_REPO(){
if [ -d  "$WORKDIR/src/llama.cpp" ]; then
  # ===============================================================================
  rm -rf "$WORKDIR/src/llama.cpp";
  # ===============================================================================
fi
}

###################################################################################
# Etape 1: Télécharger le Dépôt #
#################################
GIT_LLAMA_CLONE_REPO(){
if [ ! -d "$WORKDIR/src/llama.cpp" ]; then
  # ===============================================================================
  git clone "$GITHUB_LLAMA" "$WORKDIR/src/llama.cpp";
  # ===============================================================================
fi
}

###################################################################################
# Etape 2: Configuration de la Build #
######################################
LLAMA_CONFIG_BUILD(){
if [ -d "$WORKDIR/src/llama.cpp" ]; then
  # ===============================================================================
  cd    "$WORKDIR/src/llama.cpp";
  cmake -B build $CMAKE_ARGS;
  # ===============================================================================
fi
}

###################################################################################
# Etape 3: Construire la Build #
################################
LLAMA_BUILD_OUTPUT(){
if [ -d "$WORKDIR/src/llama.cpp" ]; then
  # ==============================================================================
   cd "$WORKDIR/src/llama.cpp";
  # ===============================================================================
   if [ !   -d "$WORKDIR/output/llama.cpp" ]; then
      mkdir -p "$WORKDIR/output/llama.cpp";
     cmake --build build --config Release -j "$BUILD_CPUS";
      #> /dev/null;
   fi
  # ===============================================================================
fi
}

###################################################################################
# Etape 4: Déplacer la Build #
##############################
LLAMA_BUILD_OUTPUT(){
if [ -d "$WORKDIR/src/llama.cpp" ]; then
  # ==============================================================================
   cd "$WORKDIR/src/llama.cpp";
  # ==============================================================================
   if [ ! -d   "$WORKDIR/output/llama.cpp" ]; then
      mkdir -p "$WORKDIR/output/llama.cpp";
      cmake --install build --prefix "$WORKDIR/output/llama.cpp"
      #> /dev/null;
      touch $WORKDIR/output/llama_Ready;
   fi
  # ==============================================================================
#else
  #echo "La fonction LLAMA_BUILD_02 est en erreur";
fi
}
