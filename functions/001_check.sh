CHECK_WORKDIR_EXIST(){
if [ !   -d "$WORKDIR" ]; then
  # ====================
  mkdir  -p "$WORKDIR";
  cd        "$WORKDIR";
  ls -la    "$WORKDIR";
  # ====================
else
  # ====================
  rm    -rf "$WORKDIR";
  mkdir -p  "$WORKDIR";
  cd        "$WORKDIR";
  ls -la    "$WORKDIR";
  # ====================
fi
}
