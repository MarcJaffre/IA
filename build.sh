#!/usr/bin/bash

# =================================================================================================
# Arrête le script immédiatement en cas d'erreur #
# ============================================== #
set -e

# =================================================================================================
# Configuration du WORKDIR #
# ======================== #
if [ -f globale.conf ]; then
  sed -i -e "s|^WORKDIR\=.*|WORKDIR=\"$(pwd)\"|g" globale.conf;
fi
# =================================================================================================
# Chargement de la configuration #
# ============================== #
source ./globale.conf;

# =================================================================================================
# Purge du système #
####################
LLAMA_PURGE_DIR_SRC
LLAMA_PURGE_DIR_OUTPUT

# =================================================================================================
# Git Hub #
###########
LLAMA_GIT_CLONE

# =================================================================================================
# Build #
#########
LLAMA_CONFIG_BUILD;   # Configuration
LLAMA_MAKE_BUILD;     # Compilation

# =================================================================================================
# Build vers output #
#####################
LLAMA_INSTALL_BUILD;


